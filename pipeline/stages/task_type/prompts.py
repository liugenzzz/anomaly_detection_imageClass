def build_level1_messages(image_data_uri: str) -> list[dict]:
    return [
        {"role": "system", "content": SYSTEM_PROMPT},
        {
            "role": "user",
            "content": [
                {"type": "text", "text": USER_PROMPT},
                {"type": "image_url", "image_url": {"url": image_data_uri}},
            ],
        },
    ]


def build_level2_messages(image_data_uri: str, task_type: str) -> list[dict]:
    if task_type not in SECOND_LEVEL_DEFINITIONS:
        raise ValueError(f"unsupported second-level task type: {task_type}")
    anomaly_types = ANOMALY_TYPES_BY_TASK[task_type]
    output_example = {
        "anomaly_scores": {anomaly_type: 0.0 for anomaly_type in anomaly_types},
        "best_anomaly_type": "其它任务类型",
        "anomaly_evidence": {anomaly_type: "" for anomaly_type in anomaly_types},
    }
    user_prompt = (
        SECOND_LEVEL_DEFINITIONS[task_type]
        + "\n\n输出约束：\n"
        + "- `best_anomaly_type` 必须是 `anomaly_scores` 中得分最高的标签。\n"
        + "- `anomaly_scores` 和 `anomaly_evidence` 必须完整包含全部候选标签。\n"
        + "- 分数不要求总和等于 1；没有充分目标异常证据时，应提高 `其它任务类型` 的分数。\n"
        + "- 证据只描述图片中直接可见的支持或排除依据。\n\n"
        + "输出格式：\n"
        + json.dumps(output_example, ensure_ascii=False, indent=2)
    )
    return [
        {"role": "system", "content": SECOND_LEVEL_SYSTEM_PROMPT},
        {
            "role": "user",
            "content": [
                {"type": "text", "text": user_prompt},
                {"type": "image_url", "image_url": {"url": image_data_uri}},
            ],
        },
    ]


